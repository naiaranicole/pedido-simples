CREATE TABLE public.usuarios (
  id_usuario uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  nome text NOT NULL,
  email text NOT NULL UNIQUE,
  ativo boolean NOT NULL DEFAULT true
);
GRANT SELECT ON public.usuarios TO authenticated;
GRANT ALL ON public.usuarios TO service_role;
ALTER TABLE public.usuarios ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Usuario ve o proprio registro" ON public.usuarios FOR SELECT TO authenticated USING (auth.uid() = id_usuario);

CREATE OR REPLACE FUNCTION public.handle_novo_usuario() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  INSERT INTO public.usuarios (id_usuario, nome, email)
  VALUES (NEW.id, COALESCE(NEW.raw_user_meta_data->>'nome', split_part(NEW.email,'@',1)), NEW.email)
  ON CONFLICT (id_usuario) DO NOTHING;
  RETURN NEW;
END $$;
CREATE TRIGGER on_auth_user_created AFTER INSERT ON auth.users FOR EACH ROW EXECUTE FUNCTION public.handle_novo_usuario();

CREATE OR REPLACE FUNCTION public.usuario_ativo() RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (SELECT 1 FROM public.usuarios WHERE id_usuario = auth.uid() AND ativo)
$$;

CREATE TABLE public.produtos (
  id_produto bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  nome text NOT NULL CHECK (length(trim(nome)) BETWEEN 1 AND 100),
  preco numeric(10,2) NOT NULL CHECK (preco > 0),
  estoque integer NOT NULL CHECK (estoque >= 0),
  ativo boolean NOT NULL DEFAULT true
);
CREATE INDEX idx_produtos_nome ON public.produtos (nome);
GRANT SELECT, INSERT, UPDATE ON public.produtos TO authenticated;
GRANT ALL ON public.produtos TO service_role;
ALTER TABLE public.produtos ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Usuarios ativos leem produtos" ON public.produtos FOR SELECT TO authenticated USING (public.usuario_ativo());
CREATE POLICY "Usuarios ativos cadastram produtos" ON public.produtos FOR INSERT TO authenticated WITH CHECK (public.usuario_ativo());
CREATE POLICY "Usuarios ativos alteram produtos" ON public.produtos FOR UPDATE TO authenticated USING (public.usuario_ativo()) WITH CHECK (public.usuario_ativo());

CREATE TYPE public.status_pedido AS ENUM ('pendente','concluido','cancelado');

CREATE TABLE public.pedidos (
  id_pedido bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data_pedido timestamptz NOT NULL DEFAULT now(),
  status public.status_pedido NOT NULL DEFAULT 'concluido',
  valor_total numeric(12,2) NOT NULL CHECK (valor_total >= 0),
  id_usuario uuid REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL
);
CREATE INDEX idx_pedidos_data ON public.pedidos (data_pedido DESC);
CREATE INDEX idx_pedidos_status ON public.pedidos (status);
GRANT SELECT ON public.pedidos TO authenticated;
GRANT ALL ON public.pedidos TO service_role;
ALTER TABLE public.pedidos ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Usuarios ativos leem pedidos" ON public.pedidos FOR SELECT TO authenticated USING (public.usuario_ativo());

CREATE TABLE public.itens_pedido (
  id_item bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id_pedido bigint NOT NULL REFERENCES public.pedidos(id_pedido) ON DELETE CASCADE,
  id_produto bigint NOT NULL REFERENCES public.produtos(id_produto) ON DELETE RESTRICT,
  quantidade integer NOT NULL CHECK (quantidade > 0),
  preco_unitario numeric(10,2) NOT NULL CHECK (preco_unitario > 0),
  subtotal numeric(12,2) NOT NULL CHECK (subtotal >= 0)
);
CREATE INDEX idx_itens_pedido ON public.itens_pedido (id_pedido);
GRANT SELECT ON public.itens_pedido TO authenticated;
GRANT ALL ON public.itens_pedido TO service_role;
ALTER TABLE public.itens_pedido ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Usuarios ativos leem itens" ON public.itens_pedido FOR SELECT TO authenticated USING (public.usuario_ativo());

-- Registro de pedido + baixa de estoque em uma unica transacao
CREATE OR REPLACE FUNCTION public.registrar_pedido(itens jsonb) RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_pedido bigint;
  v_total numeric(12,2) := 0;
  v_item jsonb;
  v_prod public.produtos%ROWTYPE;
  v_qtd integer;
BEGIN
  IF auth.uid() IS NULL OR NOT public.usuario_ativo() THEN
    RAISE EXCEPTION 'NAO_AUTORIZADO';
  END IF;
  IF itens IS NULL OR jsonb_typeof(itens) <> 'array' OR jsonb_array_length(itens) = 0 THEN
    RAISE EXCEPTION 'SEM_ITENS';
  END IF;
  IF jsonb_array_length(itens) > 50 THEN RAISE EXCEPTION 'SEM_ITENS'; END IF;

  INSERT INTO public.pedidos (status, valor_total, id_usuario) VALUES ('concluido', 0, auth.uid())
  RETURNING id_pedido INTO v_pedido;

  FOR v_item IN SELECT * FROM jsonb_array_elements(itens) LOOP
    v_qtd := (v_item->>'quantidade')::integer;
    IF v_qtd IS NULL OR v_qtd <= 0 THEN RAISE EXCEPTION 'QUANTIDADE_INVALIDA'; END IF;
    SELECT * INTO v_prod FROM public.produtos
      WHERE id_produto = (v_item->>'id_produto')::bigint AND ativo FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'PRODUTO_INEXISTENTE'; END IF;
    IF v_prod.estoque < v_qtd THEN RAISE EXCEPTION 'ESTOQUE_INSUFICIENTE'; END IF;
    UPDATE public.produtos SET estoque = estoque - v_qtd WHERE id_produto = v_prod.id_produto;
    INSERT INTO public.itens_pedido (id_pedido, id_produto, quantidade, preco_unitario, subtotal)
      VALUES (v_pedido, v_prod.id_produto, v_qtd, v_prod.preco, v_prod.preco * v_qtd);
    v_total := v_total + v_prod.preco * v_qtd;
  END LOOP;

  UPDATE public.pedidos SET valor_total = v_total WHERE id_pedido = v_pedido;
  RETURN v_pedido;
END $$;
REVOKE ALL ON FUNCTION public.registrar_pedido(jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.registrar_pedido(jsonb) TO authenticated;

